import assert from 'node:assert/strict';
import { elapsedMilliseconds, formatDuration, formatLocalTime, matchingMessageIds, messageMarkdown, publicEvents, quotedMessage, sameOriginAttachmentUrl } from '../src/chat-features.ts';
import { attachmentDraftKey, validateAttachmentFiles } from '../src/attachment-utils.ts';

const started = '2026-11-18T08:00:00Z';
assert.equal(elapsedMilliseconds({ started_at: started }, Date.parse(started) + 125000), 125000);
assert.equal(elapsedMilliseconds({ started_at: started, completed_at: '2026-11-18T08:01:02Z' }, 0), 62000, 'completed durations do not change with page clock');
assert.equal(elapsedMilliseconds({ started_at: started, duration_ms: 9876 }, 0), 9876);
assert.equal(elapsedMilliseconds({ started_at: 'invalid' }), null);
assert.equal(elapsedMilliseconds({ duration_ms: -2 }), 0);
assert.equal(formatDuration(125000), '2 分 5 秒');
assert.equal(formatDuration(3600000), '1 小时 0 分');
assert.equal(formatLocalTime('invalid'), '');
assert.ok(formatLocalTime(started).length > 8);
assert.equal(quotedMessage('one\ntwo'), '> one\n> two\n\n');
const messages = [{ id: '1', role: 'user', content: '**literal** question' }, { id: '2', role: 'assistant', content: 'answer', attachments: [{ id: 'a', name: 'DATA.CSV' }] }];
assert.deepEqual(matchingMessageIds(messages, 'LITERAL'), ['1']);
assert.deepEqual(matchingMessageIds(messages, 'data.csv'), ['2']);
assert.deepEqual(matchingMessageIds(messages, '  '), []);
assert.equal(publicEvents([{ type: 'reasoning_summary', text: 'public' }, { type: 'reasoning_raw', text: 'private' }, { type: 'usage' }, { type: 'tool' }]).length, 2);
assert.match(messageMarkdown({ id: 'a', role: 'assistant', content: '# original', created_at: started, run: { model: 'm', duration_ms: 12000 } }), /# original/);
assert.equal(attachmentDraftKey('session'), 'sciver-chat-attachments-v1:research:session');
assert.equal(validateAttachmentFiles([{ name: 'paper.PDF', size: 20_000_000 }], 9), null);
assert.match(validateAttachmentFiles([{ name: 'paper.pdf', size: 20_000_001 }]), /20 MB/);
assert.match(validateAttachmentFiles([{ name: 'paper.doc', size: 1 }]), /DOCX/);
assert.match(validateAttachmentFiles([{ name: 'empty.csv', size: 0 }]), /空文件/);
assert.match(validateAttachmentFiles([{ name: 'a.csv', size: 1 }], 10), /10 个/);
globalThis.location = new URL('https://sciver.example/research-chat/');
assert.equal(sameOriginAttachmentUrl('/api/research-chat/a/attachments/b/content'), 'https://sciver.example/api/research-chat/a/attachments/b/content');
assert.equal(sameOriginAttachmentUrl('https://evil.example/api/research-chat/a'), undefined);
assert.equal(sameOriginAttachmentUrl('javascript:alert(1)'), undefined);
assert.equal(sameOriginAttachmentUrl('/etc/passwd'), undefined);
console.log('PASS: persisted timing, local dates, raw-text search/quotes/export, public event filtering, attachment bounds and draft/url safety');
